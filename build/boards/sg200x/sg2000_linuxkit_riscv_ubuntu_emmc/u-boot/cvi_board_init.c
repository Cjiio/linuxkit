int cvi_board_init(void)
{
	/*WIFI*/
	pinmux_config(PINMUX_SDIO1);
	PINMUX_CONFIG(VIVO_CLK, XGPIOB_22);/*EN*/
	PINMUX_CONFIG(PWR_GPIO0, PWR_GPIO_0);/*WAKE*/

	/*BT*/
	PINMUX_CONFIG(UART2_RX, UART4_RX);
	PINMUX_CONFIG(UART2_TX, UART4_TX);
	PINMUX_CONFIG(UART2_CTS, UART4_CTS);
	PINMUX_CONFIG(UART2_RTS, UART4_RTS);

	/*MIPI_RST*/
	pinmux_config(PINMUX_DSI);
	PINMUX_CONFIG(CAM_MCLK0, XGPIOA_0);/*RTSX*/
	PINMUX_CONFIG(CAM_PD1, XGPIOA_4);/*ERR_FG*/
	PINMUX_CONFIG(CAM_PD0, XGPIOA_1);/*TE*/

	/*touch*/
	PINMUX_CONFIG(IIC3_SCL, IIC3_SCL);
	PINMUX_CONFIG(IIC3_SDA, IIC3_SDA);
	PINMUX_CONFIG(CAM_MCLK1, XGPIOA_3);/*INT*/
	PINMUX_CONFIG(CAM_RST0, XGPIOA_2);/*RST*/

	/*sensor I2C*/
	PINMUX_CONFIG(IIC2_SDA, IIC2_SDA);
	PINMUX_CONFIG(IIC2_SCL, IIC2_SCL);

	/*sensor INT*/
	PINMUX_CONFIG(PWR_SEQ3, PWR_GPIO_5);/*AXP2101*/
	PINMUX_CONFIG(PWR_SEQ2, PWR_GPIO_4);/*HUSB320*/
	PINMUX_CONFIG(PWR_BUTTON1, PWR_GPIO_8);/*LSM6DSRTR*/

	return 0;
}

